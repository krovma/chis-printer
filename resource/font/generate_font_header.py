"""Generate 1bpp 16-pixel character cells from the project's display strings."""
from __future__ import annotations

import argparse
import re
from pathlib import Path

from fontTools.ttLib import TTFont
from PIL import Image, ImageDraw, ImageFont


SCRIPT_DIR = Path(__file__).resolve().parent
DEFAULT_FONT = SCRIPT_DIR.parent / "ZhengGeDianHei-16.ttf"
DEFAULT_TEXT_HEADER = SCRIPT_DIR.parent / "text" / "display_texts.h"
DEFAULT_OUTPUT = SCRIPT_DIR / "generated_font.h"
TRANSLATION_RE = re.compile(
    r"\{\s*[^,]+,\s*[^,]+,\s*(?:u8)?\"((?:\\.|[^\"\\])*)\"\s*\}"
)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--font", type=Path, default=DEFAULT_FONT)
    parser.add_argument("--text-header", type=Path, default=DEFAULT_TEXT_HEADER)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--threshold", type=int, default=128, help="Grayscale threshold for 1bpp output")
    return parser.parse_args()


def fail(message: str) -> None:
    raise SystemExit(f"error: {message}")


def load_display_strings(path: Path) -> list[str]:
    try:
        source = path.read_text(encoding="utf-8")
    except OSError as exc:
        fail(f"cannot read {path}: {exc}")
    values = [match.group(1) for match in TRANSLATION_RE.finditer(source)]
    if not values:
        fail(f"no translation values found in {path}")
    return values


def decode_cpp_string(value: str) -> str:
    return value.replace(r'\"', '"').replace(r"\\", "\\")


def required_codepoints(values: list[str]) -> list[int]:
    codepoints = sorted({ord(character) for value in values for character in decode_cpp_string(value)})
    if not codepoints:
        fail("display text table contains no characters")
    return codepoints


def validate_font(font_path: Path, codepoints: list[int]) -> None:
    font = TTFont(font_path)
    cmap = {}
    for table in font["cmap"].tables:
        cmap.update(table.cmap)
    missing = [f"U+{codepoint:04X}" for codepoint in codepoints if codepoint not in cmap]
    if missing:
        fail(f"font is missing required codepoints: {', '.join(missing)}")


def render_glyph(font: ImageFont.FreeTypeFont, codepoint: int, threshold: int) -> tuple[int, bytes]:
    character = chr(codepoint)
    width = 8 if codepoint <= 0x7F else 16
    row_stride = width // 8
    image = Image.new("L", (width, 16), 0)
    draw = ImageDraw.Draw(image)
    # Pillow reports this font's 16px glyph top at y=5. Align that top to row 0.
    draw.text((0, -5), character, font=font, fill=255)

    pixels = image.load()
    data = bytearray(row_stride * 16)
    for y in range(16):
        for x in range(width):
            if pixels[x, y] >= threshold:
                data[y * row_stride + x // 8] |= 0x80 >> (x & 7)
    return width, bytes(data)


def cpp_array(data: bytes) -> str:
    lines = []
    for offset in range(0, len(data), 16):
        chunk = data[offset : offset + 16]
        lines.append("    " + ", ".join(f"0x{value:02X}" for value in chunk) + ",")
    return "\n".join(lines)


def generate(font_path: Path, text_header: Path, output: Path, threshold: int) -> None:
    if not 0 <= threshold <= 255:
        fail("--threshold must be between 0 and 255")
    values = load_display_strings(text_header)
    codepoints = required_codepoints(values)
    validate_font(font_path, codepoints)
    raster_font = ImageFont.truetype(font_path, 16)

    lines = [
        "// SPDX-License-Identifier: GPL-3.0-or-later AND OFL-1.1",
        "// Copyright (C) 2026 Ken(github.com/krovma)",
        "// Copyright notice applies to generated C++ code; font-derived glyph data: OFL-1.1.",
        "// Generated by resource/font/generate_font_header.py; do not edit by hand.",
        "// Source: ZhengGeDianHei-16.ttf; cells are top-aligned 1bpp MSB-first rows.",
        f"// Required display strings: {text_header.name}; threshold: {threshold}",
        "",
        "#pragma once",
        "",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "namespace firmware_font {",
        "",
        "struct Glyph {",
        "    std::uint32_t codepoint;",
        "    std::uint8_t width;",
        "    std::uint8_t row_stride;",
        "    const std::uint8_t* rows;",
        "};",
        "",
    ]

    glyph_names: list[tuple[int, str, int]] = []
    for codepoint in codepoints:
        width, data = render_glyph(raster_font, codepoint, threshold)
        name = f"GLYPH_U{codepoint:04X}"
        glyph_names.append((codepoint, name, width))
        lines.extend(
            [
                f"inline constexpr std::uint8_t {name}_ROWS[] = {{",
                cpp_array(data),
                "};",
                "",
            ]
        )

    lines.append("inline constexpr Glyph GLYPHS[] = {")
    for codepoint, name, width in glyph_names:
        lines.append(f"    {{0x{codepoint:04X}, {width}, {width // 8}, {name}_ROWS}},")
    lines.extend(
        [
            "};",
            "",
            "inline constexpr std::size_t GLYPH_COUNT = sizeof(GLYPHS) / sizeof(GLYPHS[0]);",
            "",
            "inline const Glyph* find_glyph(const std::uint32_t codepoint) noexcept {",
            "    switch (codepoint) {",
        ]
    )
    for index, (codepoint, _, _) in enumerate(glyph_names):
        lines.append(f"        case 0x{codepoint:04X}: return &GLYPHS[{index}];")
    lines.extend(
        [
            "        default: return nullptr;",
            "    }",
            "}",
            "",
            "}  // namespace firmware_font",
            "",
        ]
    )
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"generated {len(glyph_names)} glyphs -> {output}")


def main() -> None:
    args = parse_args()
    generate(args.font.resolve(), args.text_header.resolve(), args.output.resolve(), args.threshold)


if __name__ == "__main__":
    main()
